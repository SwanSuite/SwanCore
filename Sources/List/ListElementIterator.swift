import Foundation

/// A high-performance, thread-safe iteration contract for traversing structural elements within a collection topology.
///
/// Provides sequential traversal hooks supporting deterministic early-interruption and
/// deferred lazy maintenance operations outside critical execution sections.
public protocol ListElementIterator {
    associatedtype Element

    /// Sequentially traverses collection elements driven by explicit starting and stepping property key paths.
    ///
    /// Supports conditional early-termination based on the output of the provided `interruptHandler`.
    ///
    /// - Parameters:
    ///   - start: A key path pointing to the initial entry element of the sequence (e.g., `\.head` or `\.tail`).
    ///   - next: A key path on the element level specifying the subsequent traversal step direction (e.g., `\.next` or `\.prev`).
    ///   - interruptHandler: An isolated closure executing on each element. Return `true` to immediately halt execution and return the current element; otherwise, return `false` to continue traversal.
    /// - Returns: The specific element that triggered early termination, or `nil` if the entire sequence chain was fully depleted.
    /// - Throws: Re-throws any error generated by the custom user closure or structural maintenance routines.
    @discardableResult @inlinable @inline(__always)
    func forEachElement(
        start: KeyPath<Self, Element?>,
        next: KeyPath<Element, Element?>,
        interruptHandler: (Element) throws -> Bool
    ) rethrows -> Element?

    /// Performs background routine sweeps or lazy resource cleanup operations on the targeted element during iteration passes.
    ///
    /// - Parameter element: The specific structural node instance currently undergoing validation.
    /// - Returns: `true` if the element remains structurally valid and traversal should proceed; `false` if the element is empty/defunct and should be skipped.
    @inlinable @inline(__always)
    func maintainance(element: Element) -> Bool
}

public extension ListElementIterator {

    /// Executes an uninterrupted sequential traversal pass over elements from a given anchor down to the termination boundary.
    ///
    /// - Parameters:
    ///   - start: A key path pointing to the initial entry element of the sequence.
    ///   - next: A key path specifying the subsequent traversal step direction.
    ///   - handler: An isolated closure invoked on every structural element in the chain.
    /// - Throws: Re-throws any error intercepted from the provided `handler`.
    @inlinable @inline(__always)
    func forEachElement(
        start: KeyPath<Self, Element?>,
        next: KeyPath<Element, Element?>,
        handler: (Element) throws -> Void
    ) rethrows {
        try forEachElement(start: start, next: next, interruptHandler: { element in
            try handler(element)
            return false
        })
    }

    /// Default blueprint maintenance routine that unconditionally validates all elements without executing collection mutations.
    @inlinable @inline(__always)
    func maintainance(element: Element) -> Bool { true }
}

public extension ListElementIterator where Self: ElementRemover, Element: Emptiable {

    /// Automatically excises depleted wrapper containers from the topology sequence directly during active traversal passes.
    ///
    /// Enforces a zero-cost, lazy "garbage-collection" mechanism specifically tailored for sweeping stale entries inside weak collections.
    ///
    /// - Parameter element: The node element currently undergoing inspection.
    /// - Returns: `false` if the element is structurally empty and has been purged from the sequence; otherwise, `true`.
    @inlinable @inline(__always)
    func maintainance(element: Element) -> Bool {
        if element.isEmpty {
            remove(element)
            return false
        }
        return true
    }
}


// MARK: - implementation

public extension ListElementIterator where Self: HasRWLock {

    /// Default blueprint layout executing thread-safe sequence iteration via a Lock Dropping strategy.
    ///
    /// Instantly acquires the shared `readLock` strictly to copy the state cursor and buffer the `next` step pointer.
    /// The lock is explicitly **released** before invoking `maintainance` and user-provided closures.
    /// This prevents holding locks over unknown execution depths, entirely avoiding deadlocks under complex cascade operations.
    ///
    /// By buffering the `next` pointer ahead of time within a stable lock state, the loop remains fully deterministic
    /// even if the `current` node gets concurrently modified or erased from a parallel thread thread-pool.
    @discardableResult @inlinable @inline(__always)
    func forEachElement(
        start: KeyPath<Self, Element?>,
        next: KeyPath<Element, Element?>,
        interruptHandler: (Element) throws -> Bool
    ) rethrows -> Element? {
        lock.readLock()
        var cursor = self[keyPath: start]
        while let current = cursor {
            let next = current[keyPath: next]
            lock.unlock()
            // Maintenance checks and user codes execute safely outside the exclusive lock path
            if try maintainance(element: current) && interruptHandler(current) {
                return current
            }
            lock.readLock()
            cursor = next
        }
        lock.unlock()
        return nil
    }
}

// MARK: - Specialized Topology Anchors

public extension ListElementIterator where Self: HasHead {

    /// Launches a forward iteration path starting directly from the `head` pointer toward trailing adjacent connections (`next`).
    ///
    /// - Parameter interruptHandler: A validation closure returning `true` to halt execution.
    /// - Returns: The targeted element that forced early termination, or `nil` if depleted.
    @discardableResult @inlinable @inline(__always)
    func forwardElementIterator(interruptHandler: (Element) throws -> Bool) rethrows -> Element? {
        try forEachElement(start: \.head, next: \.next, interruptHandler: interruptHandler)
    }

    /// Launches an uninterrupted forward traversal sweep starting from the `head` anchor down to the tail end.
    ///
    /// - Parameter handler: A closure executed for each structural element.
    @inlinable @inline(__always)
    func forwardElementIterator(handler: (Element) throws -> Void) rethrows {
        try forEachElement(start: \.head, next: \.next, handler: handler)
    }
}


public extension ListElementIterator where Self: HasTail {

    /// Launches a backward iteration path starting directly from the `tail` anchor toward preceding adjacent connections (`prev`).
    ///
    /// - Parameter interruptHandler: A validation closure returning `true` to halt execution.
    /// - Returns: The targeted element that forced early termination, or `nil` if depleted.
    @discardableResult @inlinable @inline(__always)
    func backwardElementIterator(interruptHandler: (Element) throws -> Bool) rethrows -> Element? {
        try forEachElement(start: \.tail, next: \.prev, interruptHandler: interruptHandler)
    }

    /// Launches an uninterrupted backward traversal sweep starting from the `tail` anchor down to the head end.
    ///
    /// - Parameter handler: A closure executed for each structural element.
    @inlinable @inline(__always)
    func backwardElementIterator(handler: (Element) throws -> Void) rethrows {
        try forEachElement(start: \.tail, next: \.prev, handler: handler)
    }
}


// MARK: - Symmetric Composite Interface

public extension ListElementIterator where Self: HasHead & HasTail {

    /// Performs an uninterrupted traversal pass over collection elements along the specified layout direction orientation axis.
    ///
    /// - Parameters:
    ///   - direction: The iteration route orientation (`.forward` to move away from head, `.backward` to move away from tail). Defaults to `.forward`.
    ///   - handler: An isolated closure executed on each element item.
    @inlinable @inline(__always)
    func forEachElement(_ direction: ListDirection = .forward, handler: (Element) throws -> Void) rethrows {
        switch direction {
        case .forward: try forwardElementIterator(handler: handler)
        case .backward: try backwardElementIterator(handler: handler)
        }
    }

    /// Scans the collection layout along the chosen direction path axis to locate the first instance satisfying a given condition predicate.
    ///
    /// - Parameters:
    ///   - direction: The structural orientation traversal route to enforce. Defaults to `.forward`.
    ///   - predicate: An execution test checking if an element qualifies as a match.
    /// - Returns: The first element instance meeting the condition, or `nil` if no matches are found.
    @inlinable @inline(__always)
    func firstElement(_ direction: ListDirection = .forward, where predicate: (Element) throws -> Bool) rethrows -> Element? {
        switch direction {
        case .forward: try forwardElementIterator(interruptHandler: predicate)
        case .backward: try backwardElementIterator(interruptHandler: predicate)
        }
    }
}
