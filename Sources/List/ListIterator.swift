/// A high-performance iteration contract specializing in traversing high-level business payloads within object containers.
///
/// Inherits structural traversal mechanics from `ListElementIterator` and flattens access to inner data blocks,
/// completely isolating developers from low-level pointer management and routing wrapper infrastructures.
public protocol ListIterator: ListElementIterator where Element: ObjectContainer {

    /// Sequentially traverses business payload elements driven by explicit starting and stepping property key paths.
    ///
    /// Supports conditional early-termination based on the output of the payload `interruptHandler`.
    ///
    /// - Parameters:
    ///   - start: A key path pointing to the initial entry element of the sequence (e.g., `\.head` or `\.tail`).
    ///   - next: A key path on the element level specifying the subsequent traversal step direction (e.g., `\.next` or `\.prev`).
    ///   - interruptHandler: An isolated closure executing on each unwrapped business item. Return `true` to immediately halt execution and return the current payload; otherwise, return `false` to continue traversal.
    /// - Returns: The specific business payload item that triggered early termination, or `nil` if the entire sequence chain was fully depleted.
    /// - Throws: Re-throws any error generated by the custom user closure or structural maintenance routines.
    @discardableResult @inlinable @inline(__always)
    func forEach(
        start: KeyPath<Self, Element?>,
        next: KeyPath<Element, Element?>,
        interruptHandler: (Element.T) throws -> Bool
    ) rethrows -> Element.T?

    /// Executes an uninterrupted sequential traversal pass over business payloads from a given anchor down to the termination boundary.
    ///
    /// - Parameters:
    ///   - start: A key path pointing to the initial entry element of the sequence.
    ///   - next: A key path specifying the subsequent traversal step direction.
    ///   - handler: An isolated closure invoked on every business payload item in the chain.
    /// - Throws: Re-throws any error intercepted from the provided `handler`.
    @inlinable @inline(__always)
    func forEach(
        start: KeyPath<Self, Element?>,
        next: KeyPath<Element, Element?>,
        handler: (Element.T) throws -> Void
    ) rethrows
}

public extension ListIterator {

    /// Default blueprint implementation for conditional payload traversal.
    ///
    /// Unwraps the underlying `object` from the container on each iteration step and routes it directly to the handler closure.
    @discardableResult @inlinable @inline(__always)
    func forEach(
        start: KeyPath<Self, Element?>,
        next: KeyPath<Element, Element?>,
        interruptHandler: (Element.T) throws -> Bool
    ) rethrows -> Element.T? {
        try forEachElement(start: start, next: next, interruptHandler: { element in
            try interruptHandler(element.object)
        })?.object
    }

    /// Default blueprint implementation for uninterrupted payload traversal.
    ///
    /// Unwraps the underlying `object` from the container on each iteration step and routes it directly to the handler closure.
    @inlinable @inline(__always)
    func forEach(
        start: KeyPath<Self, Element?>,
        next: KeyPath<Element, Element?>,
        handler: (Element.T) throws -> Void
    ) rethrows {
        try forEachElement(start: start, next: next, handler: { element in
            try handler(element.object)
        })
    }
}

public extension ListIterator where Self: HasHead {

    /// Launches a forward iteration path starting directly from the `head` pointer toward trailing adjacent items, passing unwrapped payloads to the execution closure.
    ///
    /// - Parameter interruptHandler: A validation closure returning `true` to halt execution.
    /// - Returns: The targeted payload item that forced early termination, or `nil` if depleted.
    @discardableResult @inlinable @inline(__always)
    func forwardIterator(interruptHandler: (Element.T) throws -> Bool) rethrows -> Element.T? {
        try forEach(start: \.head, next: \.next, interruptHandler: interruptHandler)
    }

    /// Launches an uninterrupted forward traversal sweep starting from the `head` anchor down to the tail end, passing unwrapped payloads to the execution closure.
    ///
    /// - Parameter handler: A closure executed for each business payload item.
    @inlinable @inline(__always)
    func forwardIterator(handler: (Element.T) throws -> Void) rethrows {
        try forEach(start: \.head, next: \.next, handler: handler)
    }
}

public extension ListIterator where Self: HasTail {

    /// Launches a backward iteration path starting directly from the `tail` anchor toward preceding adjacent items, passing unwrapped payloads to the execution closure.
    ///
    /// - Parameter interruptHandler: A validation closure returning `true` to halt execution.
    /// - Returns: The targeted payload item that forced early termination, or `nil` if depleted.
    @discardableResult @inlinable @inline(__always)
    func backwardIterator(interruptHandler: (Element.T) throws -> Bool) rethrows -> Element.T? {
        try forEach(start: \.tail, next: \.prev, interruptHandler: interruptHandler)
    }

    /// Launches an uninterrupted backward traversal sweep starting from the `tail` anchor down to the head end, passing unwrapped payloads to the execution closure.
    ///
    /// - Parameter handler: A closure executed for each business payload item.
    @inlinable @inline(__always)
    func backwardIterator(handler: (Element.T) throws -> Void) rethrows {
        try forEach(start: \.tail, next: \.prev, handler: handler)
    }
}

// MARK: - Symmetric Composite Interface

public extension ListIterator where Self: HasHead & HasTail {

    /// Performs an uninterrupted traversal pass over business payloads along the specified layout direction orientation axis.
    ///
    /// - Parameters:
    ///   - direction: The iteration route orientation (`.forward` to move away from head, `.backward` to move away from tail). Defaults to `.forward`.
    ///   - handler: An isolated closure executed on each business payload item.
    @inlinable @inline(__always)
    func forEach(_ direction: ListDirection = .forward, handler: (Element.T) throws -> Void) rethrows {
        switch direction {
        case .forward: try forwardIterator(handler: handler)
        case .backward: try backwardIterator(handler: handler)
        }
    }

    /// Scans the collection layout along the chosen direction path axis to locate the first business payload satisfying a given condition predicate.
    ///
    /// - Parameters:
    ///   - direction: The structural orientation traversal route to enforce. Defaults to `.forward`.
    ///   - predicate: An execution test checking if an item qualifies as a match.
    /// - Returns: The first payload instance meeting the condition, or `nil` if no matches are found.
    @inlinable @inline(__always)
    func first(_ direction: ListDirection = .forward, where predicate: (Element.T) throws -> Bool) rethrows -> Element.T? {
        switch direction {
        case .forward: try forwardIterator(interruptHandler: predicate)
        case .backward: try backwardIterator(interruptHandler: predicate)
        }
    }
}
