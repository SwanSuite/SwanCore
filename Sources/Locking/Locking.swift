import Foundation
import os

/// A structural layout contract specifying that the conforming container owns a unique, non-copyable exclusive lock.
///
/// By exposing the lock via a static associated type, it prevents runtime existential type erasure overhead,
/// enabling the compiler to completely flatten synchronized execution blocks inside performance-critical traits.
public protocol HasLock: AnyObject {
    associatedtype Lock: Locking

    /// The unique, non-copyable exclusive synchronization primitive driving the container's isolation policy.
    var lock: Lock { get }
}


/// A high-performance synchronization primitive specification enforcing unique ownership.
///
/// By suppressing the default `Copyable` capability, implementations of this protocol
/// are statically prevented from being copied, eliminating accidental lock replication defects.
public protocol Locking: Sendable, ~Copyable {
    init()

    /// Acquires the lock exclusively. Blocks the calling thread if already held.
    borrowing func lock()

    /// Releases the exclusive lock.
    borrowing func unlock()

    /// Tries to acquire the exclusive lock without blocking the calling thread.
    ///
    /// - Returns: `true` if the lock was successfully acquired; otherwise, `false`.
    borrowing func lockIfAvailable() -> Bool
}


extension Locking {

    /// Executes a closure within an exclusive critical section guaranteed by the non-copyable lock.
    ///
    /// This method enforces strict isolation by requiring both the closure and its return value
    /// to conform to `Sendable`, matching modern high-performance system APIs.
    ///
    /// - Parameter body: A throwing, isolated closure containing the critical operations.
    /// - Returns: The strictly sendable result of the closure.
    /// - Throws: Re-throws any error generated by the provided closure.
    @discardableResult
    @inline(__always)
    public borrowing func withLock<R: Sendable>(_ body: @Sendable () throws -> R) rethrows -> R {
        self.lock()
        defer { self.unlock() }
        return try body()
    }
}


// MARK: - Conformances

extension OSAllocatedUnfairLock: Locking where State == Void {}

extension NSLock: Locking {
    /// Tries to acquire the standard lock instantly.
    @inlinable @inline(__always) public borrowing func lockIfAvailable() -> Bool { `try`() }
}

public final class Mutex: Locking, @unchecked Sendable {
    @usableFromInline internal var mutex = pthread_mutex_t()

    @inlinable public init() { pthread_mutex_init(&mutex, nil) }
    @inlinable deinit { pthread_mutex_destroy(&mutex) }

    @inlinable @inline(__always) public borrowing func lock() { pthread_mutex_lock(&mutex) }
    @inlinable @inline(__always) public borrowing func unlock() { pthread_mutex_unlock(&mutex) }
    @inlinable @inline(__always) public borrowing func lockIfAvailable() -> Bool { pthread_mutex_trylock(&mutex) == 0 }
}

/// A zero-cost, non-copyable dummy lock structure designed for single-threaded benchmarks.
@frozen public struct VoidLock: Locking {
    @inlinable @inline(__always) public init() {}
    @inlinable @inline(__always) borrowing public func lock() {}
    @inlinable @inline(__always) borrowing public func unlock() {}
    @inlinable @inline(__always) borrowing public func lockIfAvailable() -> Bool { true }
}
