/// A structural layout contract specifying that the conforming container owns an execution lock.
///
/// This design trait acts as a synchronization bridge under Swift 6 strict concurrency.
/// It enables external protocol extensions (traits) to seamlessly acquire and release
/// the container's critical section boundaries without needing explicit knowledge
/// of the concrete data structure's layout.
public protocol HasLock: AnyObject {

    /// The thread-safe synchronization primitive driving the container's isolation policy.
    var lock: any Locking { get }
}

/// A high-performance synchronization primitive specification enforcing unique ownership.
///
/// By suppressing the default `Copyable` capability, implementations of this protocol
/// are statically prevented from being copied, eliminating accidental lock replication defects.
public protocol Locking: ~Copyable, Sendable {

    /// Acquires the lock exclusively. Blocks the calling thread if already held.
    func lock()

    /// Releases the exclusive lock.
    func unlock()

    /// Tries to acquire the exclusive lock without blocking the calling thread.
    ///
    /// - Returns: `true` if the lock was successfully acquired; otherwise, `false`.
    func lockIfAvailable() -> Bool
}

extension Locking {

    /// Executes a closure within an exclusive critical section guaranteed by the non-copyable lock.
    ///
    /// This method enforces strict isolation by requiring both the closure and its return value
    /// to conform to `Sendable`, matching modern high-performance system APIs.
    ///
    /// - Parameter body: A throwing, isolated closure containing the critical operations.
    /// - Returns: The strictly sendable result of the closure.
    /// - Throws: Re-throws any error generated by the provided closure.
    @discardableResult
    @inline(__always)
    public func withLock<R: Sendable>(_ body: @Sendable () throws -> R) rethrows -> R {
        self.lock()
        defer { self.unlock() }
        return try body()
    }
}
