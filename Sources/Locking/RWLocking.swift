import os

/// A structural layout contract specifying that the conforming container owns a unique, non-copyable shared-exclusive lock.
///
/// By exposing the lock via a static associated type, it prevents runtime existential type erasure overhead,
/// enabling the compiler to completely flatten synchronized execution blocks inside performance-critical traits.
public protocol HasRWLock: AnyObject {
    associatedtype Lock: RWLocking

    /// The unique, non-copyable shared-exclusive synchronization primitive driving the container's isolation policy.
    var lock: Lock { get }
}


/// A high-performance shared-exclusive synchronization primitive specification enforcing unique ownership.
///
/// By suppressing the default `Copyable` capability via `~Copyable`, implementations of this protocol
/// can reside entirely on the stack as non-copyable structures, eliminating lock replication defects.
/// It permits multiple concurrent threads to hold read-access simultaneously,
/// while strictly isolating mutations behind an exclusive write lock path.
public protocol RWLocking: Sendable, ~Copyable {
    init()

    /// Acquires a shared lock optimized for non-mutating read operations.
    ///
    /// Multiple threads can hold a read lock concurrently as long as no writer holds the exclusive lock.
    borrowing func readLock()

    /// Acquires an exclusive lock for writing.
    ///
    /// Blocks the calling thread if any other thread holds a read or write lock.
    borrowing func writeLock()

    /// Releases the lock uniformly for both read and write states.
    borrowing func unlock()

    /// Tries to acquire a shared read lock without blocking the calling thread.
    ///
    /// - Returns: `true` if the read lock was successfully acquired; otherwise, `false`.
    borrowing func tryReadLock() -> Bool

    /// Tries to acquire an exclusive write lock without blocking the calling thread.
    ///
    /// - Returns: `true` if the write lock was successfully acquired; otherwise, `false`.
    borrowing func tryWriteLock() -> Bool
}


extension RWLocking {

    /// Executes a non-mutating closure within a shared read critical section guaranteed by the lock.
    ///
    /// - Parameter body: A throwing, isolated closure containing non-mutating operations.
    /// - Returns: The strictly sendable result of the closure.
    /// - Throws: Re-throws any error generated by the provided closure.
    @discardableResult @inline(__always)
    public borrowing func withReadLock<R: Sendable>(_ body: @Sendable () throws -> R) rethrows -> R {
        self.readLock()
        defer { self.unlock() }
        return try body()
    }

    /// Executes a mutating closure within an exclusive write critical section guaranteed by the lock.
    ///
    /// - Parameter body: A throwing, isolated closure containing mutations.
    /// - Returns: The strictly sendable result of the closure.
    /// - Throws: Re-throws any error generated by the provided closure.
    @discardableResult @inline(__always)
    public borrowing func withWriteLock<R: Sendable>(_ body: @Sendable () throws -> R) rethrows -> R {
        self.writeLock()
        defer { self.unlock() }
        return try body()
    }
}


// MARK: - Conformances

// High-performance Exclusive Fallback for Apple's native lock under RWLocking requirements.
extension OSAllocatedUnfairLock: RWLocking where State == Void {

    /// Maps shared read access directly to the native exclusive lock path.
    @inlinable @inline(__always)
    public borrowing func readLock() { lock() }

    /// Maps exclusive write access directly to the native exclusive lock path.
    @inlinable @inline(__always)
    public borrowing func writeLock() { lock() }

    /// Tries to acquire a shared read lock exclusively without blocking.
    @inlinable @inline(__always)
    public borrowing func tryReadLock() -> Bool { lockIfAvailable() }

    /// Tries to acquire an exclusive write lock without blocking.
    @inlinable @inline(__always)
    public borrowing func tryWriteLock() -> Bool { lockIfAvailable() }
}

public final class RWLock: RWLocking, @unchecked Sendable {
    @usableFromInline internal var rwlock = pthread_rwlock_t()

    @inlinable public init() { pthread_rwlock_init(&rwlock, nil) }
    deinit { pthread_rwlock_destroy(&rwlock) }

    @inlinable @inline(__always) public borrowing func readLock() { pthread_rwlock_rdlock(&rwlock) }
    @inlinable @inline(__always) public borrowing func writeLock() { pthread_rwlock_wrlock(&rwlock) }
    @inlinable @inline(__always) public borrowing func unlock() { pthread_rwlock_unlock(&rwlock) }
    @inlinable @inline(__always) public borrowing func tryReadLock() -> Bool { pthread_rwlock_tryrdlock(&rwlock) == 0 }
    @inlinable @inline(__always) public borrowing func tryWriteLock() -> Bool { pthread_rwlock_trywrlock(&rwlock) == 0 }
}

extension VoidLock: RWLocking {
    @inlinable @inline(__always) public borrowing func readLock() {}
    @inlinable @inline(__always) public borrowing func writeLock() {}
    @inlinable @inline(__always) public borrowing func tryReadLock() -> Bool { true }
    @inlinable @inline(__always) public borrowing func tryWriteLock() -> Bool { true }
}
